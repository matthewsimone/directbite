// ============================================================================
// ordrCore.mjs — shared helpers for the vendored Ordr POS pricing module
// ============================================================================
//
// supabase/functions/_shared/ordr-core/ holds a BYTE-IDENTICAL copy of the
// Ordr POS pricing module (ordr-pos: src/core/money.ts + src/core/order/*.ts,
// non-test files), laid out exactly as under src/core/ so its relative `.ts`
// imports (`../money.ts`) resolve unchanged. VENDORED.json records where the
// bytes came from and the sha256 of every file.
//
// The vendored files are never edited here. A fix belongs in ordr-pos; then
// re-run scripts/vendor-ordr-core.mjs. Used by vendor-ordr-core.mjs and
// check-ordr-core.mjs.
// ============================================================================

import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const VENDOR_DIR = path.join(REPO_ROOT, 'supabase/functions/_shared/ordr-core');
export const MANIFEST_PATH = path.join(VENDOR_DIR, 'VENDORED.json');

/** Directory inside ordr-pos that maps onto VENDOR_DIR. */
export const SOURCE_ROOT = 'src/core';

/**
 * Which source files are vendored, as paths relative to SOURCE_ROOT:
 * money.ts and every non-test .ts directly under order/.
 */
export function isVendoredPath(rel) {
  if (rel === 'money.ts') return true;
  return /^order\/[^/]+\.ts$/.test(rel) && !rel.endsWith('.test.ts');
}

/**
 * Non-pricing vendored ordr-pos files (DIRECTBITE-HANDOFF item 4): byte-identical
 * copies of src/core/<name> in their own directory + manifest, so they are
 * drift-checked like ordr-core/ but NEVER part of pricingModuleHash.
 */
export const EXT_VENDOR_DIR = path.join(REPO_ROOT, 'supabase/functions/_shared/ordr-core-ext');
export const EXT_MANIFEST_PATH = path.join(EXT_VENDOR_DIR, 'VENDORED.json');
export const EXT_FILES = ['availability.ts', 'cardData.ts'];

export function sha256(buf) {
  return createHash('sha256').update(buf).digest('hex');
}

/**
 * Generated identity constants for the pos-v1 function (so it does not depend
 * on JSON-import bundling). Lives OUTSIDE ordr-core/ (that directory holds
 * vendored bytes only). Written by vendor-ordr-core.mjs, verified byte-exact
 * by check-ordr-core.mjs.
 */
export const MODULE_INFO_PATH = path.join(REPO_ROOT, 'supabase/functions/_shared/pos-v1/ordrCoreInfo.generated.ts');

/**
 * pricingModuleHash: sha256 (hex) of the manifest in `sha256sum` format,
 * "<sha256>  <path>\n" per file, sorted by path. Reproducible in ordr-pos with
 * `cd src/core && sha256sum <files in path order> | sha256sum`.
 */
export function pricingModuleHash(files) {
  const text = Object.keys(files).sort().map((p) => `${files[p]}  ${p}\n`).join('');
  return sha256(Buffer.from(text, 'utf8'));
}

export function renderModuleInfo({ sourceRepo, sourceCommit, files }) {
  return [
    '// AUTO-GENERATED by scripts/vendor-ordr-core.mjs. DO NOT EDIT.',
    '// Verified against ordr-core/VENDORED.json by scripts/check-ordr-core.mjs.',
    `// Source: ${sourceRepo}`,
    '',
    '/** sha256 of the vendored files in sha256sum format (see scripts/lib/ordrCore.mjs). */',
    `export const PRICING_MODULE_HASH = '${pricingModuleHash(files)}';`,
    '',
    '/** ordr-pos commit the vendored bytes were copied from. */',
    `export const SOURCE_COMMIT = '${sourceCommit}';`,
    '',
  ].join('\n');
}

/** Stable JSON for the manifest: sorted file keys, 2-space indent, trailing newline. */
export function serializeManifest({ sourceRepo, sourceCommit, files }) {
  const sorted = Object.fromEntries(Object.keys(files).sort().map((k) => [k, files[k]]));
  return `${JSON.stringify({ sourceRepo, sourceCommit, files: sorted }, null, 2)}\n`;
}
